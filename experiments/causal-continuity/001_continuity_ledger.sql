-- Causal continuity ledger (experimental; branch-only)
-- Keeps historical claims intact while separating proposed change from later evidence.

create table if not exists public.continuity_ledger (
  id bigint generated by default as identity primary key,
  user_id text not null,
  created_at timestamptz not null default now(),
  source_kind text not null check (source_kind in ('user','agent','archive','external','system')),
  source_ref text,
  event_summary text not null,
  candidate_rule text,
  predicted_consequence text,
  falsification_condition text,
  status text not null default 'candidate'
    check (status in ('candidate','active','verified','contradicted','refuted','superseded')),
  evidence_for integer not null default 0,
  evidence_against integer not null default 0,
  last_tested_at timestamptz,
  supersedes_id bigint references public.continuity_ledger(id),
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists continuity_ledger_user_status_created_idx
  on public.continuity_ledger (user_id, status, created_at desc);

create table if not exists public.continuity_evidence (
  id bigint generated by default as identity primary key,
  ledger_id bigint not null references public.continuity_ledger(id) on delete cascade,
  observed_at timestamptz not null default now(),
  source_kind text not null check (source_kind in ('interaction','archive','external','manual_test','system')),
  source_ref text,
  opportunity text not null,
  observed_behavior text not null,
  verdict text not null check (verdict in ('supports','contradicts','neutral')),
  rationale text,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists continuity_evidence_ledger_observed_idx
  on public.continuity_evidence (ledger_id, observed_at desc);

-- Deliberately no trigger that promotes candidate -> verified.
-- Verification must be based on a later observation, not the same event that proposed the rule.
